#!/usr/bin/env bash
# make perf-index
#
# Regenerates perf/INDEX.md from every run's summary.json. Generated, never
# hand-edited: an append-only log that humans maintain becomes a list of
# unfilled placeholders, which is worse than no log at all.

set -euo pipefail
source "$(dirname "${BASH_SOURCE[0]}")/lib.sh"

require_tools jq

OUT="$PERF_DIR/INDEX.md"

{
  echo "# Perf run index"
  echo
  echo "Generated by \`make perf-index\`. Do not edit — changes are overwritten."
  echo
  echo "Compliance is counted exactly at the scenario's target threshold. A run"
  echo "marked \`dropped\` did not offer the load it asked for and is not"
  echo "comparable; a run marked \`tainted\` had pods restart underneath it."
  echo
  echo "| run | scenario | topology | shape | completed | success | within target | verdict | notes |"
  echo "|---|---|---|---|---|---|---|---|---|"
} > "$OUT"

found=0
while IFS= read -r summary; do
  dir="$(dirname "$summary")"
  health="$dir/health.json"
  flags=""
  [ -f "$health" ] && [ "$(jq -r '.tainted // false' "$health")" = "true" ] && flags="tainted"
  [ "$(jq -r '.results.dropped_iterations // 0' "$summary")" != "0" ] && flags="${flags:+$flags, }dropped"
  [ -f "$health" ] && [ "$(jq -r '.observed // true' "$health")" = "false" ] && flags="${flags:+$flags, }health n/a"

  jq -r --arg flags "$flags" --arg rel "${dir#"$REPO_ROOT/"}" '
    def pct(v): if v == null then "n/a" else ((v * 100 * 1000 | round) / 1000 | tostring) + "%" end;
    "| [\(.run_id)](../\($rel)) | \(.scenario) | \(.topology) | \(.load.shape) \(.load.tps // (.load.steps | tostring)) | " +
    "\(.results.completed) | \(pct(.results.success_rate)) | " +
    "\(pct(.results.compliance_at_target)) @ \(.slo.target)s | " +
    "\(if .verdict.slo_met then "MET" else "NOT MET" end) | \($flags) |"
  ' "$summary" >> "$OUT" 2>/dev/null || true
  found=$((found + 1))
done < <(find "$RESULT_ROOT" -type f -name summary.json 2>/dev/null | sort -r)

if [ "$found" = "0" ]; then
  echo "" >> "$OUT"
  echo "_No runs recorded yet._" >> "$OUT"
fi

echo "wrote ${OUT#"$REPO_ROOT/"} ($found run(s))"
